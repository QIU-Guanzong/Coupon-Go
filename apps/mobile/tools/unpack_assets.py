"""Decode the base64-packed APK assets into apps/mobile/assets/.

Run once after cloning, before `flutter pub get`:
    python3 tools/unpack_assets.py

Reads assets-packed/manifest.json, verifies SHA-256 per file, and writes:
    apps/mobile/assets/images/*.png|gif
    apps/mobile/assets/fonts/Roboto-*.ttf

The packed files are base64 text because the snapshot-push channel used to
publish this repository only accepts UTF-8 text. The decoded files are the
real assets; they are git-ignored and regenerated by this script.
Provenance: Coupon GO! 1.2.6 APK unpack, included per Miso's instruction
(copyright-holder claim by Miso, not independently verified).
"""
import base64
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MOBILE = os.path.dirname(HERE)
PACKED = os.path.join(MOBILE, "assets-packed")
OUT = os.path.join(MOBILE, "assets")


def main() -> int:
    manifest_path = os.path.join(PACKED, "manifest.json")
    with open(manifest_path) as f:
        manifest = json.load(f)
    ok = 0
    for entry in manifest["assets"]:
        src = os.path.join(PACKED, entry["target"] + ".b64")
        with open(src) as f:
            data = base64.b64decode("".join(f.read().split()))
        digest = hashlib.sha256(data).hexdigest()
        if digest != entry["sha256"]:
            print(f"MISMATCH {entry['target']}: {digest} != {entry['sha256']}")
            return 1
        if len(data) != entry["bytes"]:
            print(f"SIZE MISMATCH {entry['target']}")
            return 1
        dst = os.path.join(OUT, entry["target"])
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, "wb") as f:
            f.write(data)
        ok += 1
    print(f"unpacked {ok} assets into {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
